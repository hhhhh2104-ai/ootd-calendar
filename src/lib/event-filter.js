const EXCLUDE_WORDS = [
  // 운동
  '운동', '점핑', '헬스', '필라테스', '요가', 'pt',
  // 미용
  '네일', '뿌염', '염색', '컷트', '커트', '앞머리', '펌', '속눈썹', '마사지', '에스테', '뷰티', '헤어',
  '클리닉', '르비쥬', '쁘띠', '제거', '왁싱', '피부과', '미용',
  // 병원
  '한의원', '치과', '잇몸', '스케일링', '병원', '단대', '내과', '외과', '재활', '엠알아이', 'mri', '검사',
  '안과', '검진', '접종', '진료', '편사', '약국', '정형', '산부인과', '이비인후과',
  // 차·잡일·회사 업무
  '주유', '세차', '블루핸즈', '공업사', '엔진오일', '수리', '해지', '당근', '마트', '애사비', '보험', '은행',
  '택배', '실사', '티비',
];

const EXCLUDE_PATTERNS = [
  /\d+\s*회(?!식|의)/, // 회차만 적힌 운동·시술 (예: "7시 17회", "5회차") — 회식은 남긴다
  /생일/, // 생일 알림 (생신·생파처럼 실제로 모인 일정은 남는다)
  /^x$/i,
];

export function isExcludedTitle(title) {
  const t = (title || '').trim();
  if (!t) return true;
  if (EXCLUDE_PATTERNS.some((re) => re.test(t))) return true;
  const n = t.replace(/\s+/g, '').toLowerCase();
  return EXCLUDE_WORDS.some((w) => n.includes(w));
}
